"""Shared setup for the knowledge-base <-> memory integration tests (T1-T7).

Everything here is synthetic and committed under ``tests/fixtures/kb_memory``:
a small Knowledge-Hub tree (``notes/``), the memories that cite it
(``corpus.json``), an evaluation question set (``eval.json``) and recorded
outputs for the OCR adapter (``pdftotext_restore_report.xhtml``,
``pdftotext_safe_ledger.xhtml``, ``ocr_mcp_recorded.json``).
The PDF and PNG originals are generated byte for byte by :func:`synthetic_pdf`
and :func:`synthetic_png`, so the recorded OCR output matches them.

``notes_factory`` is a ``runtime.recall.adapters`` factory: a recall provider
over memfw's own notes index (FTS) that emits ``kh:<path>#<heading>`` refs, so
``mode=two_stage`` finds note sections without QMD. ``qdrant_factory`` wraps
the Qdrant adapter's factory with a deterministic in-process embedder. Not
collected by pytest (no ``test_`` prefix).
"""

