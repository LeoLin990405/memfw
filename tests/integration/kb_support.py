# --- a recall provider over memfw's own notes index -------------------------------------


class NotesIndexProvider:
    """``kh:`` path candidates from ``memfw.notes.NotesIndex`` (FTS); never any text.

    Privacy is not decided here: the coordinator's ``kh:`` resolver
    (``NotesSegmentResolver``) re-reads each section and applies the clearance.
    """

    lexical = True
    projection_version = ""

    def __init__(self, name: str, db: Path, *, tenant: str = "") -> None:
        self.name = name
        self.db = Path(db)
        self.tenant = tenant

    def available(self) -> Any:
        from memfw.ports import Availability

        return Availability.ok() if self.db.is_file() else Availability.missing("no_index")

    def search(self, query: str, *, limit: int, **kwargs: Any) -> list[Any]:
        from memfw_adapter_qmd.paths import note_ref

        from memfw.notes import NotesIndex
        from memfw.ports import Candidate, ProviderUnavailable

        if not self.db.is_file():
            raise ProviderUnavailable("no_index")
        if kwargs.get("tenant", "") != self.tenant:
            return []
        hits = NotesIndex(self.db).search(query, limit=limit, mode="fts")
        out: list[Any] = []
        for hit in hits:
            ref = note_ref(hit.path, hit.heading)
            if len(ref) > 512 or any(ref == c.ref for c in out):
                continue
            out.append(
                Candidate(
                    ref=ref,
                    ref_kind="path",
                    score=float(hit.score) if math.isfinite(hit.score) else 0.0,
                    provider=self.name,
                    rank=len(out) + 1,
                )
            )
        return out[:limit]


def notes_factory(settings: Mapping[str, Any]) -> NotesIndexProvider:
    """``runtime.recall.adapters`` factory: options ``index`` (required), ``name``."""

    unknown = set(settings) - {"vault", "embedder", "name", "index", "tenant"}
    if unknown:
        raise ValueError("unknown notes provider settings")
    index = settings.get("index")
    if not isinstance(index, str) or not index:
        raise ValueError("index is required")
    return NotesIndexProvider(
        str(settings.get("name", "kh-notes")), Path(index), tenant=str(settings.get("tenant", ""))
    )


_WORD = re.compile(r"\w+")


class WordsEmbedder:
    """Deterministic bag-of-words vectors (16 buckets), in process."""

    dimension = 16
    fingerprint = "kb-words-16"

    def embed(self, texts: Sequence[str], *, role: str = "document") -> list[list[float]]:
        del role
        out = []
        for text in texts:
            vector = [0.0] * self.dimension
            for word in _WORD.findall(text.lower()):
                vector[int(hashlib.sha256(word.encode()).hexdigest(), 16) % self.dimension] += 1
            norm = math.sqrt(sum(v * v for v in vector)) or 1.0
            out.append([v / norm if any(vector) else 0.25 for v in vector])
        return out


def qdrant_factory(settings: Mapping[str, Any]) -> Any:
    """The Qdrant adapter's factory with :class:`WordsEmbedder` (no embedding service)."""

    from memfw_adapter_qdrant import factory

    merged = dict(settings)
    merged["embedder"] = WordsEmbedder()
    return factory(merged)


# --- the evaluation ---------------------------------------------------------------------


@dataclass
class Question:
    id: str
    query: str
    memories: tuple[str, ...] = ()
    notes: tuple[str, ...] = ()
    attachments: tuple[str, ...] = ()  # attachment names from corpus.json

    @property
    def targets(self) -> int:
        return len(self.memories) + len(self.notes) + len(self.attachments)


@dataclass
class Recall:
    found: int = 0
    total: int = 0
    by_source: dict[str, list[int]] = field(default_factory=dict)
    misses: list[str] = field(default_factory=list)

    def add(self, source: str, hit: bool, label: str) -> None:
        self.found += int(hit)
        self.total += 1
        counts = self.by_source.setdefault(source, [0, 0])
        counts[0] += int(hit)
        counts[1] += 1
        if not hit:
            self.misses.append(label)

    @property
    def value(self) -> float:
        return self.found / self.total if self.total else 0.0

    def as_dict(self) -> dict[str, Any]:
        return {
            "recall_at_10": round(self.value, 4),
            "found": self.found,
            "targets": self.total,
            "by_source": {
                name: round(hit / total, 4) for name, (hit, total) in sorted(self.by_source.items())
            },
        }


def questions(data: Any) -> list[Question]:
    return [
        Question(
            id=item["id"],
            query=item["query"],
            memories=tuple(item.get("memories", ())),
            notes=tuple(item.get("notes", ())),
            attachments=tuple(item.get("attachments", ())),
        )
        for item in data["questions"]
    ]


# --- building the whole thing -----------------------------------------------------------

REMOTE = frozenset({"public", "shared"})
EVERY = frozenset({"public", "shared", "local-private"})


@dataclass
class KB:
    root: Path  # the vault
    notes_root: Path  # the Knowledge-Hub copy, also the attachments root "kh"
    notes_db: Path
    repository: Any
    attachments: dict[str, str]  # name -> attachment id
    proxy_index: Path
    corpus: dict[str, Any]


def _fake_poppler(work: Path, recording: Path) -> tuple[str, str]:
    """Stand-ins for ``pdftotext``/``pdfinfo`` that print a recorded output."""

    work.mkdir(parents=True, exist_ok=True)
    pages = recording.read_text(encoding="utf-8").count("<page ")
    tool = work / "fake-pdftotext"
    tool.write_text(f'#!/bin/sh\ncat "{recording}"\n', encoding="utf-8")
    info = work / "fake-pdfinfo"
    info.write_text(f"#!/bin/sh\nprintf 'Pages:          {pages}\\n'\n", encoding="utf-8")
    for path in (tool, info):
        path.chmod(0o700)
    return str(tool), str(info)


def ocr_backend(spec: Mapping[str, Any], work: Path) -> Any:
    """The OCR adapter backend a corpus attachment names, over recorded output only."""

    from memfw_adapter_ocr import McpOcrBackend, PdftotextBackend

    if spec["backend"] == "pdftotext":
        tool, info = _fake_poppler(work, FIXTURES / spec["recording"])
        return PdftotextBackend(tool, pdfinfo=info)
    env = {
        "FAKE_MCP_RECORDED": str(FIXTURES / "ocr_mcp_recorded.json"),
        "FAKE_MCP_LOG": str(work / "mcp-log.jsonl"),
        "FAKE_MCP_MODE": spec.get("mode", "normal"),
    }
    work.mkdir(parents=True, exist_ok=True)
    return McpOcrBackend(
        [sys.executable, "-I", str(OCR_FIXTURES / "fake_mcp_server.py")],
        env=env,
        poll_seconds=0.01,
    )


def _evidence(values: Sequence[str], attachments: Mapping[str, str]) -> list[str]:
    out = []
    for value in values:
        for name, identifier in attachments.items():
            value = value.replace("{att:" + name + "}", identifier)
        out.append(value)
    return out


def build_kb(tmp_path: Path) -> KB:
    """Vault + notes copy + notes index + referenced attachments + OCR proxies + memories."""

    from memfw_adapter_ocr import generate_proxy, write_proxy

    from memfw.core.repository import Repository
    from memfw.index import MemoryIndex
    from memfw.index.proxies import ensure_proxy_index
    from memfw.notes import NotesIndex

    corpus = load_json("corpus.json")
    notes_root = copy_notes(tmp_path / "kh")
    notes_db = tmp_path / "notes.sqlite3"
    NotesIndex(notes_db).index(notes_root)
    counter = iter(range(1, 1_000_000))
    repository = Repository(
        tmp_path / "vault",
        clock=lambda: NOW,
        id_factory=lambda: hashlib.sha256(f"kb:{next(counter)}".encode()).hexdigest()[:32],
    )
    repository.init()
    config = repository.read_config()
    config["attachments_roots"] = {"kh": str(notes_root)}
    repository.configure(config)
    attachments: dict[str, str] = {}
    for item in corpus["attachments"]:
        record = repository.add_attachment(
            "kh:" + item["path"],
            reference=True,
            privacy=item["privacy"],
            media_type=item["media_type"],
        ).record
        attachments[item["name"]] = record.id
        work = tmp_path / "ocr" / item["name"]
        candidate = generate_proxy(
            notes_root / item["path"],
            backend=ocr_backend(item["ocr"], work),
            attachment_id=record.id,
            sha256=record.sha256,
            media_type=item["media_type"],
            privacy=item["privacy"],
            clearance=EVERY,
            now=NOW,
        )
        out = write_proxy(work / "proxy.json", candidate)
        repository.import_proxy(record.id, out, privacy=item["privacy"])
    for item in corpus["memories"]:
        repository.add(
            item["title"],
            item["body"],
            memory_id=item["id"],
            privacy=item["privacy"],
            evidence=_evidence(item["evidence"], attachments) or None,
            epistemic=item.get("epistemic"),
        )
    MemoryIndex(repository.index_path).rebuild(repository)
    index = ensure_proxy_index(repository, now=NOW)
    assert index is not None
    return KB(
        root=repository.root,
        notes_root=notes_root,
        notes_db=notes_db,
        repository=repository,
        attachments=attachments,
        proxy_index=index.path,
        corpus=corpus,
    )


def unified_coordinator(kb: KB, *, clearance: frozenset[str] = REMOTE) -> Any:
    """FTS over memories + the notes index + attachment proxies, one coordinator."""

    from memfw.recall import Coordinator
    from memfw.recall.builtin import (
        FtsProvider,
        NotesSegmentResolver,
        ProxyProvider,
        ProxySegmentResolver,
        default_resolvers,
    )
    from memfw.runtime import ensure_search_index

    notes = NotesSegmentResolver(kb.notes_root, kb.notes_db, clearance=clearance)
    return Coordinator(
        [
            FtsProvider(kb.root, prepare=ensure_search_index),
            NotesIndexProvider("kh-notes", kb.notes_db),
            ProxyProvider(kb.root, clearance=clearance, index_path=kb.proxy_index),
        ],
        resolvers=default_resolvers(
            kb.root,
            schemes={"kh": notes},
            extra={"attachment_segment": ProxySegmentResolver(kb.proxy_index, tenant="")},
        ),
    )


def score(result: Any, question: Question, attachments: Mapping[str, str], into: Recall) -> None:
    memory_ids = list(result.ids)[:10]
    segments = list(result.segments)[:10]
    notes = {seg.path for seg in segments if seg.source == "notes"}
    found_attachments = {seg.path for seg in segments if seg.source == "attachments"}
    for memory_id in question.memories:
        into.add("memories", memory_id in memory_ids, f"{question.id}:{memory_id}")
    for path in question.notes:
        into.add("notes", path in notes, f"{question.id}:{path}")
    for name in question.attachments:
        into.add("attachments", attachments[name] in found_attachments, f"{question.id}:{name}")


class LongBudget:
    """Wraps a recall provider and gives it a long budget of its own (30 s).

    The coordinator still waits only for the configured ``timeout_seconds``, so
    a slow service hits the coordinator's deadline (``timeout``), never the
    adapter's own socket deadline first.
    """

    def __init__(self, inner: Any) -> None:
        self.inner = inner
        self.name = inner.name
        self.lexical = getattr(inner, "lexical", False)
        self.projection_version = getattr(inner, "projection_version", "")

    def available(self) -> Any:
        return self.inner.available()

    def search(self, query: str, **kwargs: Any) -> Any:
        from memfw.ports import RecallBudget

        kwargs["budget"] = RecallBudget(timeout_seconds=30.0)
        return self.inner.search(query, **kwargs)


def qmd_notes_long_budget_factory(settings: Mapping[str, Any]) -> LongBudget:
    """``memfw_adapter_qmd:notes_factory`` behind :class:`LongBudget`."""

    from memfw_adapter_qmd import notes_factory

    return LongBudget(notes_factory(settings))
