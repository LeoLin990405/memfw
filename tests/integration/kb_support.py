def copy_notes(target: Path) -> Path:
    """A private copy of the committed notes tree plus the generated originals."""

    shutil.copytree(NOTES, target)
    (target / "scans").mkdir()
    (target / "images").mkdir()
    (target / "scans" / "restore-report.pdf").write_bytes(synthetic_pdf(SCAN_PAGES))
    (target / "scans" / "safe-ledger.pdf").write_bytes(synthetic_pdf(PRIVATE_SCAN_PAGES))
    (target / "images" / "rack-photo.png").write_bytes(synthetic_png(*RACK_SIZE))
    return target


