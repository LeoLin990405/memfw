def leaks(payload: Any, *, echo: Sequence[str] = ()) -> int:
    """How many times a private marker shows up in what an exit returned.

    ``echo``: the query text the exit repeats back (``"query": ...``), which is
    the caller's own input, not a leak; it is removed before counting.
    """

    text = payload if isinstance(payload, str) else json.dumps(payload, ensure_ascii=False)
    for value in echo:
        text = text.replace(value, "")
    lowered = text.lower()
    return sum(lowered.count(marker) for marker in MARKERS)


