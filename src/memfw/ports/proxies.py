@dataclass(frozen=True, slots=True)
class Coverage:
    """How much of the original the proxy covers. ``partial`` is shown with every hit."""

    status: str
    detail: str | None = None

    def __post_init__(self) -> None:
        if self.status not in COVERAGE_STATUSES:
            raise ProxyFormatError("coverage.status must be full or partial")
        if self.detail is not None:
            _label(self.detail, "coverage.detail")

    def to_json(self) -> dict[str, Any]:
        data: dict[str, Any] = {"status": self.status}
        if self.detail is not None:
            data["detail"] = self.detail
        return data

    @classmethod
    def from_json(cls, raw: Any) -> Coverage:
        if not isinstance(raw, Mapping):
            raise ProxyFormatError(
                'coverage must be an object: {"status": "full"|"partial", "detail": ...}'
            )
        unknown = set(raw) - {"status", "detail"}
        if unknown:
            raise ProxyFormatError("unknown coverage keys: " + ", ".join(sorted(map(str, unknown))))
        detail = raw.get("detail")
        return cls(
            status=raw.get("status"),  # type: ignore[arg-type]
            detail=None if detail is None else _label(detail, "coverage.detail"),
        )


def check_producer(raw: Any) -> str | dict[str, str]:
    """``{"tool", "version"}``, ``"human"`` or ``"app-manual:<app>"``."""

    if raw == "human":
        return "human"
    if isinstance(raw, str):
        if _APP_MANUAL_RE.fullmatch(raw):
            _label(raw.split(":", 1)[1], "producer app", limit=100)
            return raw
        raise ProxyFormatError(
            'producer must be {"tool", "version"}, "human" or "app-manual:<app>"'
        )
    if not isinstance(raw, Mapping) or set(raw) != {"tool", "version"}:
        raise ProxyFormatError(
            'producer must be {"tool", "version"}, "human" or "app-manual:<app>"'
        )
    return {
        "tool": _label(raw["tool"], "producer.tool", limit=100),
        "version": _label(raw["version"], "producer.version", limit=100),
    }


def clean_text(value: Any, what: str = "segment text") -> str:
    """A segment's text: newlines normalised, outer whitespace stripped, not empty.

    ``\r\n``, ``\r``, U+2028 and U+2029 become ``\n``. Any other C0 or C1
    control character (``\t`` is kept), the bidirectional override and
    isolate characters (U+202A–U+202E, U+2066–U+2069) and the invisible
    marks U+200B, U+200E, U+200F, U+061C and U+FEFF are refused, so a proxy
    cannot hide or reorder text when shown.
    """

    if not isinstance(value, str):
        raise ProxyFormatError(f"{what} must be a string")
    text = (
        value.replace("\r\n", "\n")
        .replace("\r", "\n")
        .replace("\u2028", "\n")
        .replace("\u2029", "\n")
        .strip()
    )
    if not text:
        raise ProxyFormatError(f"{what} is empty")
    if len(text) > MAX_SEGMENT_CHARS:
        raise ProxyFormatError(f"{what} is over {MAX_SEGMENT_CHARS} characters")
    if any(
        char not in "\n\t" and (_FORBIDDEN_CHAR.match(char) or _INVISIBLE_CHAR.match(char))
        for char in text
    ):
        raise ProxyFormatError(
            f"{what} has a control, bidirectional override or invisible format character"
        )
    if any(line.lstrip().startswith(_MARKER_PREFIX) for line in text.split("\n")):
        raise ProxyFormatError(f"{what} contains a memfw segment marker")
    return text


@dataclass(frozen=True, slots=True)
class ProxySegment:
    """One piece of text and where it is. ``speaker`` only in transcripts (never verified)."""

    text: str
    locator: Locator = field(default_factory=Locator)
    speaker: str | None = None
    confidence: float | None = None

    def __post_init__(self) -> None:
        object.__setattr__(self, "text", clean_text(self.text))
        if self.speaker is not None:
            object.__setattr__(self, "speaker", _label(self.speaker, "segment speaker", limit=100))
        if self.confidence is not None:
            value = _number(self.confidence, "segment confidence")
            if not 0 <= value <= 1:
                raise ProxyFormatError("segment confidence must be within 0..1")
            object.__setattr__(self, "confidence", _round(value))

    def to_json(self) -> dict[str, Any]:
        data: dict[str, Any] = {"text": self.text}
        locator = self.locator.to_json()
        if locator:
            data["locator"] = locator
        if self.speaker is not None:
            data["speaker"] = self.speaker
        if self.confidence is not None:
            data["confidence"] = _json_number(self.confidence)
        return data


@dataclass(frozen=True, slots=True)
class ProxyImport:
    """A parsed, validated proxy file with canonical locators.

    :meth:`to_json` writes it back in the version-1 format (canonical units,
    so without ``coordinates``); an adapter can build one and call it.
    """

    kind: str
    source_sha256: str
    coverage: Coverage
    segments: tuple[ProxySegment, ...]
    producer: str | Mapping[str, str] | None = None
    attachment_id: str | None = None
    created_at: str | None = None
    supersedes: str | None = None
    privacy: str | None = None
    language: str | None = None
    source: SourceDimensions = field(default_factory=SourceDimensions)

    def __post_init__(self) -> None:
        if self.kind not in PROXY_KINDS:
            raise ProxyFormatError("kind must be one of: " + ", ".join(PROXY_KINDS))
        if not isinstance(self.source_sha256, str) or not _SHA_RE.fullmatch(self.source_sha256):
            raise ProxyFormatError("source_sha256 must be 64 lowercase hex characters")
        if self.kind == "keyframes" and self.coverage.status != "partial":
            raise ProxyFormatError("a keyframes proxy covers only its frames: coverage partial")
        if not self.segments:
            raise ProxyFormatError("segments must not be empty")
        if len(self.segments) > MAX_SEGMENTS:
            raise ProxyFormatError(f"at most {MAX_SEGMENTS} segments")
        if self.kind != "transcript" and any(s.speaker is not None for s in self.segments):
            raise ProxyFormatError("only a transcript has speakers")
        if self.producer is not None:
            object.__setattr__(self, "producer", check_producer(self.producer))
        if self.attachment_id is not None and not _ATT_RE.fullmatch(str(self.attachment_id)):
            raise ProxyFormatError("attachment_id must be att-<uuid7>")
        if self.supersedes is not None and not PROXY_ID_RE.fullmatch(str(self.supersedes)):
            raise ProxyFormatError("supersedes must be prx-<uuid7>")
        if self.created_at is not None:
            _timestamp(self.created_at)
        if self.privacy is not None and self.privacy not in ("public", "shared", "local-private"):
            raise ProxyFormatError("privacy must be public, shared or local-private")
        if self.language is not None and not _LANG_RE.fullmatch(self.language):
            raise ProxyFormatError("language must be a BCP 47 tag such as en or zh-Hans")

    def to_json(self) -> dict[str, Any]:
        data: dict[str, Any] = {
            "format": PROXY_FORMAT,
            "version": PROXY_FORMAT_VERSION,
            "kind": self.kind,
            "source_sha256": self.source_sha256,
        }
        if self.attachment_id is not None:
            data["attachment_id"] = self.attachment_id
        data["coverage"] = self.coverage.to_json()
        if self.producer is not None:
            data["producer"] = (
                dict(self.producer) if isinstance(self.producer, Mapping) else self.producer
            )
        for key in ("created_at", "supersedes", "privacy", "language"):
            value = getattr(self, key)
            if value is not None:
                data[key] = value
        if self.kind == "transcript":
            data["speaker_labels"] = "unverified"
        source = self.source.to_json()
        if source:
            data["source"] = source
        data["segments"] = [segment.to_json() for segment in self.segments]
        return data


def _timestamp(value: Any) -> str:
    if not isinstance(value, str):
        raise ProxyFormatError("created_at must be an ISO 8601 string")
    try:
        parsed = datetime.fromisoformat(value.replace("Z", "+00:00"))
    except ValueError:
        raise ProxyFormatError("created_at must be an ISO 8601 string") from None
    if parsed.tzinfo is None:
        raise ProxyFormatError("created_at must include a timezone")
    return value


def _merge_dimensions(
    declared: SourceDimensions, known: SourceDimensions | None
) -> SourceDimensions:
    """The declared dimensions, checked against (and completed by) the known ones."""

    if known is None or known.is_empty():
        return declared
    merged: dict[str, Any] = {}
    for name in ("pages", "page_sizes", "width", "height", "duration"):
        mine, theirs = getattr(declared, name), getattr(known, name)
        empty = (None, ())
        if mine not in empty and theirs not in empty and mine != theirs:
            raise ProxyFormatError(f"source.{name} does not match the attachment")
        merged[name] = theirs if theirs not in empty else mine
    return SourceDimensions(**merged)


def parse_proxy_import(
    payload: Any,
    *,
    media_type: str,
    known: SourceDimensions | None = None,
) -> ProxyImport:
    """Validate a version-1 proxy mapping and convert its locators to canonical units.

    ``media_type`` is the attachment's; ``known`` are dimensions memfw already
    has for it (they must agree with ``source`` where both say something).
    Raises :class:`ProxyFormatError` with the first problem found; nothing is
    accepted partially.
    """

    if not isinstance(payload, Mapping):
        raise ProxyFormatError("a proxy file is one JSON object")
    missing = [key for key in _REQUIRED_KEYS if key not in payload]
    if missing:
        raise ProxyFormatError("missing required keys: " + ", ".join(missing))
    unknown = set(payload) - _TOP_KEYS
    if unknown:
        raise ProxyFormatError("unknown keys: " + ", ".join(sorted(map(str, unknown))))
    if payload["format"] != PROXY_FORMAT:
        raise ProxyFormatError(f"format must be {PROXY_FORMAT!r}")
    version = payload["version"]
    if type(version) is not int or version != PROXY_FORMAT_VERSION:
        raise ProxyFormatError(f"unsupported version {version!r} (this memfw reads 1)")
    kind = payload["kind"]
    if payload.get("speaker_labels", "unverified") != "unverified":
        raise ProxyFormatError("speaker_labels is always unverified")
    if "speaker_labels" in payload and kind != "transcript":
        raise ProxyFormatError("only a transcript has speaker_labels")
    medium = medium_for(media_type)
    space = CoordinateSpace.from_json(payload.get("coordinates"))
    source = _merge_dimensions(SourceDimensions.from_json(payload.get("source")), known)
    raw_segments = payload["segments"]
    if not isinstance(raw_segments, list):
        raise ProxyFormatError("segments must be a list")
    if len(raw_segments) > MAX_SEGMENTS:
        raise ProxyFormatError(f"at most {MAX_SEGMENTS} segments")
    segments: list[ProxySegment] = []
    for index, raw in enumerate(raw_segments, start=1):
        try:
            segments.append(_segment(raw, medium=medium, space=space, source=source))
        except ProxyFormatError as exc:
            raise ProxyFormatError(f"segment {index}: {exc}") from None
    privacy = payload.get("privacy")
    if isinstance(privacy, str):
        privacy = privacy.strip().lower()
    return ProxyImport(
        kind=kind,
        source_sha256=payload["source_sha256"],
        coverage=Coverage.from_json(payload["coverage"]),
        segments=tuple(segments),
        producer=payload.get("producer"),
        attachment_id=payload.get("attachment_id"),
        created_at=payload.get("created_at"),
        supersedes=payload.get("supersedes"),
        privacy=privacy,
        language=payload.get("language"),
        source=source,
    )


def _segment(
    raw: Any, *, medium: str, space: CoordinateSpace, source: SourceDimensions
) -> ProxySegment:
    if not isinstance(raw, Mapping):
        raise ProxyFormatError("must be an object")
    unknown = set(raw) - {"text", "locator", "speaker", "confidence"}
    if unknown:
        raise ProxyFormatError("unknown keys: " + ", ".join(sorted(map(str, unknown))))
    if "text" not in raw:
        raise ProxyFormatError("text is required")
    # Only an absent or null locator means "the whole attachment".
    where = raw.get("locator")
    if where is None:
        where = {}
    if not isinstance(where, Mapping):
        raise ProxyFormatError("locator must be an object (or null)")
    extra = set(where) - {"page", "bbox", "t", "frame"}
    if extra:
        raise ProxyFormatError("unknown locator keys: " + ", ".join(sorted(map(str, extra))))
    page = where.get("page")
    if page is not None:
        _positive_int(page, "locator.page")
    bbox = None
    if where.get("bbox") is not None:
        if medium == "pdf" and page is None:
            raise ProxyFormatError("a PDF box needs its page")
        bbox = canonical_bbox(
            where["bbox"],
            medium=medium,
            space=space,
            page_size=source.page_size(page) if page is not None else None,
            image_size=(
                (source.width, source.height)
                if source.width is not None and source.height is not None
                else None
            ),
        )
    span = None
    if where.get("t") is not None:
        values = where["t"]
        if not isinstance(values, list) or len(values) != 2:
            raise ProxyFormatError("locator.t must be [start, end]")
        span = (
            canonical_seconds(values[0], space, what="locator.t"),
            canonical_seconds(values[1], space, what="locator.t"),
        )
    frame = None
    if where.get("frame") is not None:
        frame = canonical_seconds(where["frame"], space, what="locator.frame")
    locator = check_locator(
        Locator(page=page, bbox=bbox, t=span, frame=frame), medium=medium, dimensions=source
    )
    return ProxySegment(
        text=raw["text"],
        locator=locator,
        speaker=raw.get("speaker"),
        confidence=raw.get("confidence"),
    )


def load_proxy_import(
    text: str | bytes, *, media_type: str, known: SourceDimensions | None = None
) -> ProxyImport:
    """:func:`parse_proxy_import` on JSON text (duplicate keys are refused)."""

    def no_duplicates(pairs: list[tuple[str, Any]]) -> dict[str, Any]:
        result: dict[str, Any] = {}
        for key, value in pairs:
            if key in result:
                raise ProxyFormatError(f"duplicate key {key!r}")
            result[key] = value
        return result

    try:
        payload = json.loads(text, object_pairs_hook=no_duplicates)
    except ProxyFormatError:
        raise
    except (ValueError, UnicodeDecodeError) as exc:
        raise ProxyFormatError(f"not valid JSON: {exc}") from None
    except RecursionError:
        raise ProxyFormatError("not valid JSON: nested too deeply") from None
    return parse_proxy_import(payload, media_type=media_type, known=known)


