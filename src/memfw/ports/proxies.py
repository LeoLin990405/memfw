"""The proxy import format (MM2a): text derived from an attachment, with locators. Stdlib only.

A *proxy* is the searchable text of an original (OCR of a scan, a transcript,
keyframe captions, text extracted from a PDF). memfw never runs the tool that
produces it: an adapter or a person writes one JSON file in this format and
``memfw attach proxy import <att-id> <file>`` stores it. The format is
versioned (``format`` / ``version``) and documented in
``docs/attachment-proxies.md``; version 1 is stable.

Canonical locator units (design v2.1):

* PDF: points (1/72 in), **bottom-left** origin of the page, ``page`` 1-based;
* image: pixels, **top-left** origin;
* audio and video: seconds from the start.

A producer may write boxes and times in another space and say so in
``coordinates`` (pixels at a DPI, top-left points, fractions of the page,
milliseconds); :func:`parse_proxy_import` converts them to the canonical
units, so a stored proxy only ever holds canonical locators. Every value is
checked against the dimensions of the original when they are known (declared
in ``source`` or passed as ``known``); a locator outside them is refused.

Everything here lives in ``memfw.ports`` (stdlib only) so an adapter can build
and check its output with the standalone ``memfw-ports`` wheel alone.
"""

from __future__ import annotations

import json
import math
import re
from collections.abc import Mapping, Sequence
from dataclasses import dataclass, field
from datetime import datetime
from typing import Any, Final

PROXY_FORMAT: Final = "memfw.proxy"
PROXY_FORMAT_VERSION: Final = 1
PROXY_KINDS: Final = ("ocr", "transcript", "keyframes", "extract", "caption")
COVERAGE_STATUSES: Final = ("full", "partial")
#: Media families a locator is checked against (``medium_for``).
MEDIA: Final = ("pdf", "image", "audio", "video", "other")

#: ``prx-<uuid7>``, generated by memfw at import (never written by a producer).
PROXY_ID_RE: Final = re.compile(
    r"^prx-[0-9a-f]{8}-[0-9a-f]{4}-7[0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$"
)
#: A recall ``Candidate.ref`` with ``ref_kind="attachment_segment"``: ``<proxy id>:<n>``.
SEGMENT_REF_RE: Final = re.compile(
    r"^prx-[0-9a-f]{8}-[0-9a-f]{4}-7[0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}:[1-9][0-9]{0,5}$"
)

MAX_SEGMENTS: Final = 100_000
MAX_SEGMENT_CHARS: Final = 65_536
MAX_LABEL_CHARS: Final = 200
#: Decimal places kept in canonical coordinates and times.
DECIMALS: Final = 3
_EPSILON: Final = 1e-6

_SHA_RE: Final = re.compile(r"^[0-9a-f]{64}$")
_ATT_RE: Final = re.compile(
    r"^att-[0-9a-f]{8}-[0-9a-f]{4}-7[0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$"
)
_LANG_RE: Final = re.compile(r"^[A-Za-z]{2,8}(-[A-Za-z0-9]{1,8})*$")
_APP_MANUAL_RE: Final = re.compile(r"^app-manual:[^\s\x00-\x1f\x7f]{1,100}$")
_MARKER_PREFIX: Final = "<!-- memfw:segment"
#: Invisible format characters that can disguise text: zero-width space,
#: LRM/RLM, Arabic letter mark, BOM (refused in labels and segment text).
_INVISIBLE_CHAR: Final = re.compile("[\u200b\u200e\u200f\u061c\ufeff]")
#: C0 and C1 controls, DEL, bidi embeddings/overrides and isolates (``clean_text``).
_FORBIDDEN_CHAR: Final = re.compile("[\x00-\x1f\x7f-\x9f\u202a-\u202e\u2066-\u2069]")

_TOP_KEYS: Final = frozenset(
    {
        "format",
        "version",
        "kind",
        "source_sha256",
        "attachment_id",
        "coverage",
        "producer",
        "created_at",
        "supersedes",
        "privacy",
        "language",
        "speaker_labels",
        "source",
        "coordinates",
        "segments",
    }
)
_REQUIRED_KEYS: Final = ("format", "version", "kind", "source_sha256", "coverage", "segments")
#: Locator keys each medium allows.
_LOCATOR_KEYS: Final[Mapping[str, frozenset[str]]] = {
    "pdf": frozenset({"page", "bbox"}),
    "image": frozenset({"bbox"}),
    "audio": frozenset({"t"}),
    "video": frozenset({"t", "frame"}),
    "other": frozenset({"page"}),
}


class ProxyFormatError(ValueError):
    """A proxy file (or one value in it) does not follow the format."""


def medium_for(media_type: str) -> str:
    """The locator family of an attachment's media type (``other`` when none fits)."""

    kind = media_type.strip().lower() if isinstance(media_type, str) else ""
    if kind == "application/pdf":
        return "pdf"
    for family in ("image", "audio", "video"):
        if kind.startswith(family + "/"):
            return family
    return "other"


# -- numbers --------------------------------------------------------------------------


def _number(value: Any, what: str) -> float:
    if isinstance(value, bool) or not isinstance(value, (int, float)):
        raise ProxyFormatError(f"{what} must be a number")
    try:
        number = float(value)
    except OverflowError:
        raise ProxyFormatError(f"{what} is too large") from None
    if not math.isfinite(number):
        raise ProxyFormatError(f"{what} must be finite")
    return number


def _round(value: float) -> float:
    rounded = round(value, DECIMALS)
    return 0.0 if rounded == 0 else rounded


def format_number(value: float) -> str:
    """Canonical text of a coordinate or time: at most three decimals, no trailing zeros."""

    text = f"{_round(value):.{DECIMALS}f}".rstrip("0").rstrip(".")
    return "0" if text in {"", "-0"} else text


def _positive_int(value: Any, what: str) -> int:
    if isinstance(value, bool) or not isinstance(value, int) or value < 1:
        raise ProxyFormatError(f"{what} must be a positive integer")
    return value


def _label(value: Any, what: str, *, limit: int = MAX_LABEL_CHARS) -> str:
    if not isinstance(value, str) or not value.strip():
        raise ProxyFormatError(f"{what} must be a non-empty string")
    text = value.strip()
    if len(text) > limit or any(
        not char.isprintable() or _FORBIDDEN_CHAR.match(char) or _INVISIBLE_CHAR.match(char)
        for char in text
    ):
        raise ProxyFormatError(f"{what} must be at most {limit} printable characters")
    return text


# -- dimensions and coordinate spaces -------------------------------------------------


@dataclass(frozen=True, slots=True)
class SourceDimensions:
    """What is known about the original's extent; every field optional.

    ``page_sizes`` are (width, height) in points, one per page (``pages`` of
    them) or a single size for every page. ``width``/``height`` are an
    image's pixels; ``duration`` is seconds.
    """

    pages: int | None = None
    page_sizes: tuple[tuple[float, float], ...] = ()
    width: float | None = None
    height: float | None = None
    duration: float | None = None

    def __post_init__(self) -> None:
        if self.pages is not None:
            _positive_int(self.pages, "source.pages")
        for size in self.page_sizes:
            if len(size) != 2 or min(size) <= 0:
                raise ProxyFormatError("source.page_sizes entries must be [width, height] > 0")
        if len(self.page_sizes) > 1 and self.pages != len(self.page_sizes):
            raise ProxyFormatError("source.page_sizes must list one size per page (or one size)")
        for name in ("width", "height", "duration"):
            value = getattr(self, name)
            if value is not None and not value > 0:
                raise ProxyFormatError(f"source.{name} must be positive")

    def page_size(self, page: int) -> tuple[float, float] | None:
        if not self.page_sizes:
            return None
        if len(self.page_sizes) == 1:
            return self.page_sizes[0]
        return self.page_sizes[page - 1] if 1 <= page <= len(self.page_sizes) else None

    def is_empty(self) -> bool:
        return self == SourceDimensions()

    def to_json(self) -> dict[str, Any]:
        data: dict[str, Any] = {}
        if self.pages is not None:
            data["pages"] = self.pages
        if len(self.page_sizes) == 1:
            data["page_size"] = [_json_number(value) for value in self.page_sizes[0]]
        elif self.page_sizes:
            data["page_sizes"] = [[_json_number(v) for v in size] for size in self.page_sizes]
        for name in ("width", "height", "duration"):
            value = getattr(self, name)
            if value is not None:
                data[name] = _json_number(value)
        return data

    @classmethod
    def from_json(cls, raw: Any) -> SourceDimensions:
        if raw is None:
            return cls()
        if not isinstance(raw, Mapping):
            raise ProxyFormatError("source must be an object")
        unknown = set(raw) - {"pages", "page_size", "page_sizes", "width", "height", "duration"}
        if unknown:
            raise ProxyFormatError("unknown source keys: " + ", ".join(sorted(map(str, unknown))))
        if "page_size" in raw and "page_sizes" in raw:
            raise ProxyFormatError("give source.page_size or source.page_sizes, not both")
        sizes: list[tuple[float, float]] = []
        if "page_size" in raw:
            sizes = [_pair(raw["page_size"], "source.page_size")]
        elif "page_sizes" in raw:
            listed = raw["page_sizes"]
            if not isinstance(listed, list) or not listed:
                raise ProxyFormatError("source.page_sizes must be a non-empty list")
            sizes = [_pair(item, "source.page_sizes[]") for item in listed]
        pages = raw.get("pages")
        return cls(
            pages=None if pages is None else _positive_int(pages, "source.pages"),
            page_sizes=tuple(sizes),
            width=_optional_number(raw, "width"),
            height=_optional_number(raw, "height"),
            duration=_optional_number(raw, "duration"),
        )


def _json_number(value: float) -> int | float:
    rounded = _round(value)
    return int(rounded) if rounded.is_integer() else rounded


def _pair(raw: Any, what: str) -> tuple[float, float]:
    if not isinstance(raw, list) or len(raw) != 2:
        raise ProxyFormatError(f"{what} must be [width, height]")
    return (_number(raw[0], what), _number(raw[1], what))


def _optional_number(raw: Mapping[str, Any], key: str) -> float | None:
    return None if raw.get(key) is None else _number(raw[key], f"source.{key}")


@dataclass(frozen=True, slots=True)
class CoordinateSpace:
    """How a producer wrote boxes and times. The default is the medium's canonical space.

    ``unit``: ``pt`` (PDF only), ``px`` (a PDF page rendered at ``dpi``, or an
    image) or ``fraction`` (0..1 of the page or image). ``origin``:
    ``bottom-left`` or ``top-left``. ``time_unit``: ``s`` or ``ms``.
    """

    unit: str | None = None
    origin: str | None = None
    dpi: float | None = None
    time_unit: str = "s"

    @classmethod
    def from_json(cls, raw: Any) -> CoordinateSpace:
        if raw is None:
            return cls()
        if not isinstance(raw, Mapping):
            raise ProxyFormatError("coordinates must be an object")
        unknown = set(raw) - {"unit", "origin", "dpi", "time_unit"}
        if unknown:
            raise ProxyFormatError(
                "unknown coordinates keys: " + ", ".join(sorted(map(str, unknown)))
            )
        unit, origin, time_unit = raw.get("unit"), raw.get("origin"), raw.get("time_unit", "s")
        if unit is not None and unit not in ("pt", "px", "fraction"):
            raise ProxyFormatError("coordinates.unit must be pt, px or fraction")
        if origin is not None and origin not in ("bottom-left", "top-left"):
            raise ProxyFormatError("coordinates.origin must be bottom-left or top-left")
        if time_unit not in ("s", "ms"):
            raise ProxyFormatError("coordinates.time_unit must be s or ms")
        dpi = None if raw.get("dpi") is None else _number(raw["dpi"], "coordinates.dpi")
        if dpi is not None and not dpi > 0:
            raise ProxyFormatError("coordinates.dpi must be positive")
        if dpi is not None and unit != "px":
            raise ProxyFormatError("coordinates.dpi applies only to unit px")
        return cls(unit=unit, origin=origin, dpi=dpi, time_unit=time_unit)


def canonical_bbox(
    box: Sequence[Any],
    *,
    medium: str,
    space: CoordinateSpace | None = None,
    page_size: tuple[float, float] | None = None,
    image_size: tuple[float, float] | None = None,
) -> tuple[float, float, float, float]:
    """Convert ``[x0, y0, x1, y1]`` from ``space`` to the medium's canonical units.

    The input box has ``x0 < x1`` and ``y0 < y1`` in its own space. PDF
    output is points from the page's bottom-left corner (``y0`` is the lower
    edge); image output is pixels from the top-left corner (``y0`` is the
    upper edge). Converting from a top-left origin or from fractions needs the
    page (or image) size; pixels on a PDF page need ``space.dpi``.
    """

    space = space or CoordinateSpace()
    if not isinstance(box, (list, tuple)) or len(box) != 4:
        raise ProxyFormatError("bbox must be [x0, y0, x1, y1]")
    x0, y0, x1, y1 = (_number(value, "bbox") for value in box)
    if not (x0 < x1 and y0 < y1):
        raise ProxyFormatError("bbox needs x0 < x1 and y0 < y1")
    if medium == "pdf":
        unit = space.unit or "pt"
        origin = space.origin or "bottom-left"
        size = page_size
        if unit == "px":
            if space.dpi is None:
                raise ProxyFormatError("pixel boxes on a PDF page need coordinates.dpi")
            scale = 72.0 / space.dpi
            x0, y0, x1, y1 = x0 * scale, y0 * scale, x1 * scale, y1 * scale
        flip_to = "bottom-left"
    elif medium == "image":
        unit = space.unit or "px"
        origin = space.origin or "top-left"
        if unit == "pt":
            raise ProxyFormatError("image boxes are in px or fraction, not pt")
        size = image_size
        flip_to = "top-left"
    else:
        raise ProxyFormatError(f"a {medium} attachment has no boxes")
    if unit == "fraction":
        if size is None:
            raise ProxyFormatError("fraction boxes need the page or image size in source")
        if min(x0, y0) < -_EPSILON or max(x1, y1) > 1 + _EPSILON:
            raise ProxyFormatError("fraction boxes must lie within 0..1")
        x0, x1 = x0 * size[0], x1 * size[0]
        y0, y1 = y0 * size[1], y1 * size[1]
    if origin != flip_to:
        if size is None:
            raise ProxyFormatError(f"converting a {origin} box needs the page or image size")
        y0, y1 = size[1] - y1, size[1] - y0
    result = (_round(x0), _round(y0), _round(x1), _round(y1))
    if not (result[0] < result[2] and result[1] < result[3]):
        raise ProxyFormatError("bbox is too small to keep at three decimals")
    return result


def canonical_seconds(value: Any, space: CoordinateSpace | None = None, *, what: str) -> float:
    """A time in seconds (``space.time_unit`` ``ms`` is divided by 1000)."""

    number = _number(value, what)
    if (space or CoordinateSpace()).time_unit == "ms":
        number /= 1000.0
    return _round(number)


# -- locators -------------------------------------------------------------------------


@dataclass(frozen=True, slots=True)
class Locator:
    """Where a segment is in the original, always in canonical units.

    ``page`` (1-based) and ``bbox`` for PDFs, ``bbox`` for images, ``t``
    (start, end seconds) for audio and video, ``frame`` (seconds) for one
    video keyframe. An empty locator means the whole attachment.
    """

    page: int | None = None
    bbox: tuple[float, float, float, float] | None = None
    t: tuple[float, float] | None = None
    frame: float | None = None

    def __post_init__(self) -> None:
        if self.page is not None:
            _positive_int(self.page, "locator.page")
        if self.bbox is not None:
            box = tuple(_round(_number(value, "locator.bbox")) for value in self.bbox)
            if len(box) != 4 or not (box[0] < box[2] and box[1] < box[3]) or min(box) < 0:
                raise ProxyFormatError("locator.bbox needs 0 <= x0 < x1 and 0 <= y0 < y1")
            object.__setattr__(self, "bbox", box)
        if self.t is not None:
            span = tuple(_round(_number(value, "locator.t")) for value in self.t)
            if len(span) != 2 or not 0 <= span[0] <= span[1]:
                raise ProxyFormatError("locator.t needs 0 <= start <= end")
            object.__setattr__(self, "t", span)
        if self.frame is not None:
            frame = _round(_number(self.frame, "locator.frame"))
            if frame < 0:
                raise ProxyFormatError("locator.frame must not be negative")
            object.__setattr__(self, "frame", frame)
        if self.t is not None and self.frame is not None:
            raise ProxyFormatError("a locator has t or frame, not both")

    def keys(self) -> frozenset[str]:
        return frozenset(
            name for name in ("page", "bbox", "t", "frame") if getattr(self, name) is not None
        )

    def fragment(self) -> str:
        """The URI fragment (without ``#``): ``page=3&bbox=72,600,540,640``, ``t=1.5,4``,
        ``frame=t:65``; empty for the whole attachment."""

        parts: list[str] = []
        if self.page is not None:
            parts.append(f"page={self.page}")
        if self.bbox is not None:
            parts.append("bbox=" + ",".join(format_number(value) for value in self.bbox))
        if self.t is not None:
            parts.append("t=" + ",".join(format_number(value) for value in self.t))
        if self.frame is not None:
            parts.append(f"frame=t:{format_number(self.frame)}")
        return "&".join(parts)

    def to_json(self) -> dict[str, Any]:
        data: dict[str, Any] = {}
        if self.page is not None:
            data["page"] = self.page
        if self.bbox is not None:
            data["bbox"] = [_json_number(value) for value in self.bbox]
        if self.t is not None:
            data["t"] = [_json_number(value) for value in self.t]
        if self.frame is not None:
            data["frame"] = _json_number(self.frame)
        return data

    @classmethod
    def parse(cls, fragment: str) -> Locator:
        """Parse a fragment written by :meth:`fragment` (a leading ``#`` is allowed)."""

        text = fragment[1:] if fragment.startswith("#") else fragment
        if not text:
            return cls()
        values: dict[str, Any] = {}
        for part in text.split("&"):
            key, sep, value = part.partition("=")
            if not sep or key in values or key not in ("page", "bbox", "t", "frame"):
                raise ProxyFormatError(f"invalid locator fragment: {fragment!r}")
            try:
                if key == "page":
                    if not value.isdigit():
                        raise ValueError
                    values[key] = int(value)
                elif key == "frame":
                    if not value.startswith("t:"):
                        raise ValueError
                    values[key] = float(value[2:])
                else:
                    values[key] = tuple(float(item) for item in value.split(","))
            except ValueError:
                raise ProxyFormatError(f"invalid locator fragment: {fragment!r}") from None
        return cls(**values)


def check_locator(
    locator: Locator, *, medium: str, dimensions: SourceDimensions | None = None
) -> Locator:
    """Refuse a locator the medium does not allow, or one outside the known dimensions."""

    allowed = _LOCATOR_KEYS.get(medium)
    if allowed is None:
        raise ProxyFormatError(f"unknown medium: {medium!r}")
    extra = locator.keys() - allowed
    if extra:
        raise ProxyFormatError(f"a {medium} locator cannot have " + ", ".join(sorted(extra)))
    if medium == "pdf" and locator.bbox is not None and locator.page is None:
        raise ProxyFormatError("a PDF box needs its page")
    dims = dimensions or SourceDimensions()
    if locator.page is not None and dims.pages is not None and locator.page > dims.pages:
        raise ProxyFormatError(f"page {locator.page} is past the last page ({dims.pages})")
    if locator.bbox is not None:
        size: tuple[float, float] | None
        if medium == "pdf":
            size = dims.page_size(locator.page or 1)
        else:
            size = (
                (dims.width, dims.height)
                if dims.width is not None and dims.height is not None
                else None
            )
        if size is not None and (
            locator.bbox[2] > size[0] + _EPSILON or locator.bbox[3] > size[1] + _EPSILON
        ):
            raise ProxyFormatError(
                f"bbox {locator.fragment()} lies outside the "
                f"{format_number(size[0])}x{format_number(size[1])} "
                + ("page" if medium == "pdf" else "image")
            )
    end = locator.t[1] if locator.t is not None else locator.frame
    if end is not None and dims.duration is not None and end > dims.duration + _EPSILON:
        raise ProxyFormatError(
            f"time {format_number(end)}s is past the end ({format_number(dims.duration)}s)"
        )
    return locator


